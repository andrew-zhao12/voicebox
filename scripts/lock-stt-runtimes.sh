#!/usr/bin/env bash
# Resolve optional STT dependencies without changing the main server lock.
set -euo pipefail
cd "$(dirname "$0")/.."
uv pip compile backend/requirements-faster-whisper.txt \
  --constraint backend/requirements.lock --python-version 3.12 \
  --python-platform x86_64-manylinux_2_28 --annotation-style line --no-header \
  --output-file backend/requirements-faster-whisper.lock
uv pip compile backend/requirements-nemotron.txt \
  --python-version 3.12 --python-platform x86_64-manylinux_2_28 \
  --no-emit-package torch --annotation-style line --no-header \
  --output-file backend/requirements-nemotron.lock
# torch and its CUDA dependencies come from the selected image variant's index.
# The isolated worker keeps its own pure-Python dependencies and Transformers 5.
python3 - <<'PY'
from pathlib import Path
for name in ('faster-whisper', 'nemotron'):
    path = Path(f'backend/requirements-{name}.lock')
    lines = path.read_text().splitlines()
    if name == 'nemotron':
        lines = [line for line in lines if not line.startswith(('nvidia-', 'cuda-', 'triton=='))]
    path.write_text('# Generated by scripts/lock-stt-runtimes.sh; do not edit by hand.\n' + '\n'.join(lines) + '\n')
PY

# A generic PyPI solve alone can miss constraints in the variant wheels (for
# example torch 2.11+cu128 requires setuptools<82). Validate the complete lock
# against both exact worker pins and both supported CPU architectures.
verification_dir=$(mktemp -d)
trap 'rm -rf "$verification_dir"' EXIT
verify_variant() {
    variant="$1"; version="$2"; platform="$3"
    printf '%s\n' "-r $(pwd)/backend/requirements-nemotron.lock" "torch==$version" > "$verification_dir/input.in"
    uv pip compile "$verification_dir/input.in" \
      --python-version 3.12 --python-platform "$platform" \
      --default-index https://pypi.org/simple \
      --index "https://download.pytorch.org/whl/$variant" --index-strategy unsafe-best-match \
      --output-file "$verification_dir/validated.lock" >/dev/null
}
verify_variant cpu 2.14.0+cpu x86_64-manylinux_2_28
verify_variant cpu 2.14.0+cpu aarch64-manylinux_2_28
verify_variant cu128 2.11.0+cu128 x86_64-manylinux_2_28
